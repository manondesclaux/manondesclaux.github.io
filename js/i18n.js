/* ========================================
   MÉCANIQUE DE TRADUCTION
======================================== */

const translatedAttributes = ["alt", "aria-label", "href"];

function normalizeText(text) {
    return text.replace(/\s+/g, " ").trim();
}

// Mémorise le texte français d'origine de chaque élément traduisible
const translatableTexts = [];
const translatableAttributes = [];

const textWalker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT, {
    acceptNode(node) {
        if (node.parentElement.closest(".experience-typewriter, .lang-toggle, script")) {
            return NodeFilter.FILTER_REJECT;
        }

        return translationsEN[normalizeText(node.data)]
            ? NodeFilter.FILTER_ACCEPT
            : NodeFilter.FILTER_REJECT;
    }
});

while (textWalker.nextNode()) {
    translatableTexts.push({ node: textWalker.currentNode, french: textWalker.currentNode.data });
}

document.body.querySelectorAll("*").forEach((element) => {
    translatedAttributes.forEach((attribute) => {
        const value = element.getAttribute(attribute);

        if (value && translationsEN[normalizeText(value)]) {
            translatableAttributes.push({ element, attribute, french: value });
        }
    });
});

const experienceTypewriters = Array.from(document.querySelectorAll(".experience-typewriter"))
    .map((element) => ({ element, french: normalizeText(element.textContent) }));

const languageToggle = document.querySelector(".lang-toggle");

function setLanguage(language) {
    const english = language === "en";

    translatableTexts.forEach(({ node, french }) => {
        if (!english) {
            node.data = french;
            return;
        }

        // Garde les espaces autour du texte (utiles entre un mot et une flèche ↗)
        const leadingSpace = french.match(/^\s*/)[0];
        const trailingSpace = french.match(/\s*$/)[0];

        node.data = leadingSpace + translationsEN[normalizeText(french)] + trailingSpace;
    });

    translatableAttributes.forEach(({ element, attribute, french }) => {
        element.setAttribute(attribute, english ? translationsEN[normalizeText(french)] : french);
    });

    experienceTypewriters.forEach(({ element, french }) => {
        setExperienceText(element, english ? (translationsEN[french] || french) : french);
    });

    document.documentElement.lang = language;

    // Le bouton propose toujours l'autre langue
    languageToggle.textContent = english ? "FR" : "EN";
    languageToggle.lang = english ? "fr" : "en";
    languageToggle.setAttribute(
        "aria-label",
        english ? "FR – Voir la page en français" : "EN – View this page in English"
    );

    languageToggle.dataset.language = language;
}

languageToggle.addEventListener("click", () => {
    setLanguage(languageToggle.dataset.language === "en" ? "fr" : "en");
});

// La page se charge en français ; un lien se terminant par ?lang=en l'ouvre directement en anglais
if (new URLSearchParams(window.location.search).get("lang") === "en") {
    setLanguage("en");
}
